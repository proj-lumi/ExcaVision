"""PlatformIO pre-build hook. No dotenv dependency or device secret required."""
import json
import re
from pathlib import Path
from urllib.parse import urlparse


def environment_header(project_dir, environment):
    if environment not in ("production", "staging"):
        raise ValueError("Select the production or staging PlatformIO environment")
    source = Path(project_dir) / (".env." + environment)
    if not source.is_file():
        raise ValueError("Copy %s.example to %s and configure its URL" % (source, source))
    values = {}
    for line in source.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = re.fullmatch(r"([A-Z_][A-Z0-9_]*)=(.*)", line)
        if not match:
            raise ValueError("Firmware env files accept KEY=value lines only")
        values[match[1]] = match[2].strip().strip("\"'")
    url = values.get("SUPABASE_URL", "")
    parsed = urlparse(url)
    if (parsed.scheme != "https" or not re.fullmatch(r"[a-z]{20}\.supabase\.co", parsed.netloc)
            or parsed.path not in ("", "/") or parsed.query or parsed.fragment):
        raise ValueError("SUPABASE_URL must be your hosted project's HTTPS URL, without a path")
    return ("// Generated by PlatformIO; do not commit.\n#pragma once\n"
            + "#define SUPABASE_URL " + json.dumps(url.rstrip("/")) + "\n"
            + "#define DEPLOYMENT_ENVIRONMENT " + json.dumps(environment.title()) + "\n")


if "Import" in globals():
    Import("env")  # Provided by PlatformIO/SCons, not a Python package.
    # Separate generated headers per build environment avoid cross-target races.
    output = Path(env.subst("$BUILD_DIR")) / "generated"
    output.mkdir(parents=True, exist_ok=True)
    (output / "Environment.generated.h").write_text(
        environment_header(env.subst("$PROJECT_DIR"), env["PIOENV"])
    )
    env.Append(CPPPATH=[str(output)])
